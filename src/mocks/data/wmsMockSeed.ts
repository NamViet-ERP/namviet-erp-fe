export function buildMockLedger(projectCode: string): WarehouseProjectLedgerEntryApiDto[] {
  const entries: WarehouseProjectLedgerEntryApiDto[] = [];

  for (const imp of MOCK_IMPORTS.filter(i => i.project === projectCode)) {
    entries.push({
      id: imp.id,
      kind: 'import',
      voucherCode: imp.voucherCode,
      date: imp.date,
      status: imp.status,
      itemQty: imp.items.length,
      totalValue: imp.totalValue,
    });
  }
  for (const exp of MOCK_EXPORTS.filter(e => e.project === projectCode)) {
    entries.push({
      id: exp.id,
      kind: 'export',
      voucherCode: exp.voucherCode,
      date: exp.date,
      status: exp.status,
      itemQty: exp.items.length,
      totalValue: null,
    });
  }
  for (const tf of MOCK_TRANSFERS.filter(
    t => t.project === projectCode || t.toProject === projectCode,
  )) {
    entries.push({
      id: tf.id,
      kind: 'transfer',
      voucherCode: tf.voucherCode,
      date: tf.date,
      status: tf.status,
      itemQty: tf.items.length,
      totalValue: null,
    });
  }

  return entries.sort((a, b) => b.date.localeCompare(a.date));
}
