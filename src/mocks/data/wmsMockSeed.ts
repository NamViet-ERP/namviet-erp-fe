export function projectNameByCode(code?: string): string {
  if (!code) return '—';
  return MOCK_WMS_PROJECTS.find(p => p.projectCode === code)?.projectName ?? code;
}

function invRow(
  projectCode: string,
  materialCode: string,
  materialName: string,
  unit: string,
  actual: number,
  plannedImport = 0,
  plannedExport = 0,
): WarehouseProjectInventoryApiDto {
  return {
    projectCode,
    materialCode,
    materialName,
    unit,
    plannedImportQty: plannedImport,
    plannedExportQty: plannedExport,
    actualImportQty: actual + plannedExport,
    actualExportQty: 0,
    actualInventoryQty: actual,
    plannedInventoryQty: plannedImport,
    reservedQty: 0,
  };
}

